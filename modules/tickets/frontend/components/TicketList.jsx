import { useState } from "react";
import TicketDetail from "../pages/TicketDetail";
import TicketForm from "./TicketForm";

const etiquetasEstado = {
  abierto: "Abierto",
  asignado: "Asignado",
  en_progreso: "En Progreso",
  resuelto: "Resuelto",
  cerrado: "Cerrado",
};

const iconosEstado = {
  abierto: "🟢",
  asignado: "🔵",
  en_progreso: "🟡",
  resuelto: "🟠",
  cerrado: "⚫",
};

const nivelesPiramide = {
  bajo: 1,
  medio: 2,
  alto: 3,
  critico: 4,
};

function PiramideNivel({ nivel }) {
  const total = nivelesPiramide[nivel] || 0;
  return (
    <span className="piramide-nivel" title={nivel}>
      {Array.from({ length: 4 }, (_, i) => (
        <span key={i} className={`piramide-pieza ${i < total ? "activa" : ""}`}>
          ▲
        </span>
      ))}
    </span>
  );
}

export default function TicketList({ tickets, onCambioEstado, onRefresh }) {
  const [ticketSeleccionado, setTicketSeleccionado] = useState(null);
  const [mostrarFormulario, setMostrarFormulario] = useState(false);

  if (ticketSeleccionado) {
    return (
      <TicketDetail
        ticketId={ticketSeleccionado}
        alVolver={() => {
          setTicketSeleccionado(null);
          if (onRefresh) onRefresh();
        }}
        onEstadoCambiado={onRefresh}
      />
    );
  }

  if (mostrarFormulario) {
    return (
      <TicketForm
        alGuardar={() => {
          setMostrarFormulario(false);
          if (onCambioEstado) onCambioEstado();
        }}
        alCancelar={() => setMostrarFormulario(false)}
      />
    );
  }

  if (tickets.length === 0) {
    return (
      <div className="ticket-lista-vacia">
        <p className="mensaje-info">No hay tickets que mostrar.</p>
      </div>
    );
  }

  return (
    <div className="ticket-lista">
      <table className="tickets-tabla">
        <thead>
          <tr>
            <th>ID</th>
            <th>Título</th>
            <th>Solicitante</th>
            <th>Estado</th>
            <th>Nivel</th>
            <th>Categoría</th>
            <th>Técnico</th>
            <th>Creado</th>
            <th>Cierre</th>
            <th>Tiempo</th>
            <th>Adjuntos</th>
          </tr>
        </thead>
        <tbody>
          {tickets.map((ticket) => (
            <tr
              key={ticket.id}
              className="ticket-fila"
              onDoubleClick={() => setTicketSeleccionado(ticket.id)}
            >
              <td>#{ticket.id}</td>
              <td className="titulo-ticket">{ticket.titulo}</td>
              <td>
                {ticket.usuario_nombre
                  ? `${ticket.usuario_nombre} ${ticket.usuario_apellido || ""}`
                  : "-"}
              </td>
              <td
                className="estado-icono"
                title={etiquetasEstado[ticket.estado]}
              >
                {iconosEstado[ticket.estado]}
              </td>
              <td className="nivel-icono">
                <PiramideNivel nivel={ticket.nivel_atencion} />
              </td>
              <td className="categoria-icono">
                {ticket.categoria ? (
                  <IconoCategoria
                    nombre={ticket.categoria_icono || "cog"}
                    titulo={ticket.categoria}
                  />
                ) : (
                  "-"
                )}
              </td>
              <td>
                {ticket.tecnico_nombre
                  ? `${ticket.tecnico_nombre} ${ticket.tecnico_apellido || ""}`
                  : "-"}
              </td>
              <td>
                {new Date(ticket.fecha_creacion).toLocaleDateString("es-MX")}
              </td>
              <td>
                {ticket.fecha_cierre
                  ? new Date(ticket.fecha_cierre).toLocaleDateString("es-MX")
                  : "-"}
              </td>
              <td>
                {ticket.tiempo_resolucion_segundos
                  ? formatearTiempo(ticket.tiempo_resolucion_segundos)
                  : "-"}
              </td>
              <td className="adjuntos-count">
                {ticket.adjuntos_count > 0 ? (
                  <span className="adjuntos-badge">
                    {ticket.adjuntos_count}
                  </span>
                ) : (
                  "-"
                )}
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

